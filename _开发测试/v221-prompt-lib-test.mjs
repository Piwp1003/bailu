// v221：📜 内置提示词与内置世界书——列出来、能改、能恢复默认、能整体关掉；改了真的发出去
import { chromium } from 'playwright';
import { launchBrowser, fileUrl } from './_launch.mjs';
import path from 'path';
import fs from 'fs';

const root = process.cwd();
const BAILU = fs.existsSync(path.join(root, 'js', '90-bailu-cards.js'));
const PLUG = JSON.parse(fs.readFileSync(path.join(root, '插件', '新玩法', '新玩法全家桶.json'), 'utf8'));
const browser = await launchBrowser(chromium);
const results = [];
const check = (n, ok, extra = '') => results.push({ n, ok: !!ok, extra });
const tag = BAILU ? '[白露]' : '[谷雨]';
const page = await (await browser.newContext({ viewport: { width: 1280, height: 860 } })).newPage();
const errs = []; page.on('pageerror', e => errs.push(e.message));
page.on('dialog', d => d.dismiss());
await page.route(/^https?:\/\//, r => r.abort());
await page.goto(fileUrl(path.join(root, 'index.html')));
await page.waitForFunction(() => window.__guyuBooted && typeof executePluginOnLoad === 'function' && window.gyPLOpen, { timeout: 20000 });
await page.waitForTimeout(1200);
await page.evaluate(({ PLUG }) => {
  if (window.bailuCards) window.__bailuNoBuiltin = true;
  myCharacters.push({ id: 9991, name: '顾言', persona: '温柔的医生', worldbooks: [], diaryData: { letters: [], diaries: [] } });
  PLUG.forEach(p => executePluginOnLoad(p));
}, { PLUG });
await page.waitForFunction(() => typeof gyxSpiceOpen === 'function', { timeout: 10000 });
await page.waitForTimeout(1200);
const r = await page.evaluate(async () => {
  const out = {};
  const c = myCharacters.find(x => x.id === 9991);
  humanFeelEnabled = true; tpesEnabled = true;
  gyPLOpen(); const ov = document.getElementById('gyPLOv'); const tx = ov.innerText;
  out.listed = ['人味强化协议', '时间感知协议 TPES', '约定≠已经发生', '不感知时间时的规矩', '欢喜冤家', '烟火气', '不矮化她'].every(s => tx.includes(s));
  out.tas = ov.querySelectorAll('textarea.gypl2-ta').length;
  out.defShown = !!ov.querySelector('textarea') && /人味强化协议/.test(ov.querySelector('textarea').value);
  gyPLSave('core.humanFeel', '【我自己写的人味规矩】别说教，别复读。');
  const p1 = buildBasePrompt(c, true, '');
  out.edited = p1.includes('我自己写的人味规矩') && !p1.includes('特质有刻度不是开关');
  gyPLSave('core.now', '\n现在是 {{现在}}，{{时段}}。\n');
  const n = gyNowAnchorNote(); out.vars = /现在是 \d{4}/.test(n) && !/\{\{/.test(n);
  gyPLOn(false); const p2 = buildBasePrompt(c, true, ''); out.offDefault = p2.includes('特质有刻度不是开关') && !p2.includes('我自己写的人味规矩');
  gyPLOn(true);
  gyPLReset('core.humanFeel'); const p3 = buildBasePrompt(c, true, ''); out.reset = p3.includes('特质有刻度不是开关');
  gyPLReset('core.now');
  await gyxSpiceToggle('g', 'humor', true);
  gyPLSave('spice.humor', '多讲冷笑话。');
  out.plug = /多讲冷笑话/.test(window.__gyxCtxFor('9991'));
  gyPLReset('spice.humor');
  out.plugBack = /会接梗/.test(window.__gyxCtxFor('9991'));
  if (typeof openSettingsPanel === 'function') openSettingsPanel('inject');
  await new Promise(r => setTimeout(r, 3500));
  out.entry = !!document.getElementById('gyPLEntry');
  out.mini = GY_MINI_FEATURES.some(f => f.id === 'promptLib');
  out.widget = !!(window.__gyPmW && window.__gyPmW.WD && window.__gyPmW.WD.gyPLW);
  document.querySelectorAll('#gyPLOv').forEach(x => x.remove());
  return out;
});
check(`${tag} 内置提示词页：说话的规矩、时间、相处模式 / 风格调料 / 别把她写弱都列出来，显示的是默认原文`, r.listed && r.tas >= 20 && r.defShown, JSON.stringify(r));
check(`${tag} 改了「人味强化协议」→ 发给 TA 的就是改过的；空位 {{现在}} {{时段}} 会换成实际内容`, r.edited && r.vars, JSON.stringify(r));
check(`${tag} 总开关关掉＝全用默认；单条「恢复默认」`, r.offDefault && r.reset, JSON.stringify(r));
check(`${tag} 内置世界书（风格调料）改了也跟着变，恢复默认就回来`, r.plug && r.plugBack, JSON.stringify(r));
check(`${tag} 入口：注入内容管理页顶上、小功能、小组件`, r.entry && r.mini && r.widget, JSON.stringify(r));
check(`${tag} 整个过程没有页面报错`, errs.length === 0, errs.join(' | ').slice(0, 600));
await browser.close();
const bad = results.filter(r => !r.ok);
results.forEach(r => console.log((r.ok ? '  ✅' : '  ❌') + ' ' + r.n + (r.ok ? '' : '\n       → ' + r.extra)));
console.log('\n' + (results.length - bad.length) + '/' + results.length + ' 通过');
process.exit(bad.length ? 1 : 0);
