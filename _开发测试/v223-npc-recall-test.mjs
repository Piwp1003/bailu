  const t = gyChatActsExtract('其实我很想你 [撤回]', c, false);
  out.stripped = typeof t === 'object' ? !/撤回/.test(JSON.stringify(t)) : !/\[撤回\]/.test(String(t));
  globalChats['9991'].push({ sender: 9991, text: '其实我很想你', timestamp: Date.now(), readBy: [] }); renderChatMessages();
  await sleep(6500);
  const L = globalChats['9991'];
  out.recalled = L.some(m => m.sender === 'system' && /撤回了一条消息/.test(m.text) && m.gyxRecall) && !L.some(m => m.sender === 9991 && m.text === '其实我很想你');
