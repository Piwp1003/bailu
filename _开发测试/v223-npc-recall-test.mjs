  const peek = document.querySelector('#chatMessagesArea .rc-peek'); out.peekLink = !!peek && /偷看一眼/.test(peek.textContent);
  peek && peek.click(); await sleep(400);
  const p2 = document.querySelector('#chatMessagesArea .rc-peek.seen'); out.peeked = !!p2 && /很想你/.test(p2.textContent);
  const ctx = window.__gyxCtxFor('9991'); out.ctx = /偷看到了/.test(ctx) && (BAILU || /\[撤回\]/.test(ctx));
